import { CARD_ASSETS } from "./cardAssets";
import { bakePlanForCard } from "./bakePlan";
import { LAYER_BAKE_SCALE } from "./bakePlan";
import {
  BAKE_STEPS,
  baseSurface,
  fulfillCover,
  layerSurface,
  loadCoverImage,
  loadLayers,
} from "./cardBakes";
import { parsePrebakedManifest, type ParsedPrebakedManifest } from "./prebakedManifest";
import { hasSurface, primeSurface } from "./surfaceCache";
import { CARD_TEMPLATES } from "./templates";
import type { CardTemplateId } from "./types";

/**
 * Prebaked-surface preparation, so the main thread never has to bake on the
 * critical path (a single bake is hundreds of ms of synchronous CPU):
 *
 *   1. Prebaked assets (baked/manifest.json next to the card's art, generated
 *      by /dev/bake) — plain image downloads, primed into the surface cache.
 *   2. Whatever is still missing when a card shows is baked synchronously by
 *      cardBakes' steps, exactly as before: the fallback for stale or absent
 *      assets.
 *
 * ensureSurfaces never rejects: any failure simply leaves the key unbaked for
 * the fallback. Covers also fulfil the hand's whenCoverBaked waiters.
 */

/** Cards with a prebaked-asset directory (generated by /dev/bake). */
const PREBAKED: Partial<Record<CardTemplateId, string>> = {
  "winter-moonlight": "/assets/cards/winter-moonlight/baked",
  "forest-letter": "/assets/cards/forest-letter/baked",
};

const inFlight = new Map<CardTemplateId, Promise<void>>();

export function ensureSurfaces(id: CardTemplateId): Promise<void> {
  let p = inFlight.get(id);
  if (!p) {
    p = prepare(id).catch(() => undefined);
    inFlight.set(id, p);
  }
  return p;
}

async function fetchManifest(base: string): Promise<ParsedPrebakedManifest | null> {
  try {
    const res = await fetch(`${base}/manifest.json`);
    if (!res.ok) return null;
    return parsePrebakedManifest(await res.json());
  } catch {
    return null;
  }
}

async function prepare(id: CardTemplateId): Promise<void> {
  const tasks = bakePlanForCard(id);
  const base = PREBAKED[id];

  // Tier 1: prebaked assets.
  if (base) {
    const manifest = await fetchManifest(base);
    if (manifest) {
      await Promise.all(
        tasks.map(async (task) => {
          if (hasSurface(task.key)) return;
          const entry = manifest.byKey.get(task.key);
          if (!entry) return;
          try {
            if ("src" in entry) {
              primeSurface(task.key, await loadCoverImage(`${base}/${entry.src}`));
            } else {
              const [normal, surface] = await Promise.all([
                loadCoverImage(`${base}/${entry.normal}`),
                loadCoverImage(`${base}/${entry.surface}`),
              ]);
              const value = { normal, surface };
              primeSurface(task.key, value);
              if (task.kind === "cover") fulfillCover(id, value);
            }
          } catch {
            // A missing or corrupt asset falls through to the main-thread bake.
          }
        }),
      );
    }
  }
}

type Idle = (cb: () => void) => void;
const whenIdle: Idle = (cb) => {
  const ric = (globalThis as { requestIdleCallback?: (cb: () => void, o?: { timeout: number }) => number })
    .requestIdleCallback;
  if (ric) ric(cb, { timeout: 2000 });
  else setTimeout(cb, 200);
};

let prebakeStarted = false;

/**
 * Prepare the remaining cards one per idle slot, so a later switch finds its
 * card ready. Surfaces arrive from the prebaked assets; the steps below only
 * do real work for keys the assets could not satisfy (the main-thread fallback).
 */
export function prebakeAllCards(skip: CardTemplateId): void {
  if (prebakeStarted || typeof window === "undefined") return;
  prebakeStarted = true;
  const queue = CARD_TEMPLATES.map((t) => t.id).filter((id) => id !== skip);
  const steps: Array<() => void> = [];
  const next = () => {
    const step = steps.shift();
    if (step) whenIdle(() => {
      step();
      next();
    });
    else if (queue.length) bakeOne(queue.shift() as CardTemplateId);
  };
  const bakeOne = (id: CardTemplateId) => {
    // Layers first: the inside-page bakes draw some of them (motifs with `src`).
    Promise.all([loadCoverImage(CARD_ASSETS[id].coverSrc), loadLayers(id), ensureSurfaces(id)])
      .then(([img, layered]) => {
        steps.push(...BAKE_STEPS.map((step) => () => step(id, img)));
        if (layered) {
          steps.push(() => baseSurface(id, layered.base));
          for (const { spec, img } of layered.items) {
            steps.push(() => layerSurface(spec.src, img, spec.box[2] * LAYER_BAKE_SCALE));
          }
        }
        next();
      })
      .catch(() => next());
  };
  next();
}
